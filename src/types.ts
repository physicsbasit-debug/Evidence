export interface Teacher {
  id: string;
  name: string;
  subject: string;
  experienceYears: number; // سنوات الخبرة
  schoolLevel: string; // الحلقة الدراسية (مثال: 1-4، 5-10، 11-12)
  email?: string;
  lastVisitDate?: string;
}

export enum EvaluationRating {
  OUTSTANDING = 1, // متميز
  GOOD = 2, // جيد
  SUITABLE = 3, // ملائم
  UNSUITABLE = 4, // غير ملائم
  NEEDS_INTERVENTION = 5, // يحتاج إلى تدخل
}

export interface IndicatorDefinition {
  id: number;
  code: string;
  title: string;
  area: "academic" | "personal" | "climate" | "teaching" | "governance";
  areaTitle: string;
  description: string;
  rubrics: {
    [key in EvaluationRating]: string;
  };
  suggestedEvidence: string[]; // أمثلة على الشواهد والأدلة المقترحة
}

export interface Recommendation {
  type: "enrichment" | "remedial" | "developmental"; // إثرائية | علاجية | تطويرية
  text: string; // نص التوصية الإجرائية
  timeframe: string; // الفترة الزمنية المقترحة للتطبيق
  responsibility: string; // مسؤولية التنفيذ (مثال: المعلم بالتنسيق مع المعلم الأول)
}

export interface VisitEvaluation {
  id: string;
  teacherId: string;
  teacherName?: string;
  date: string;
  grade: string; // الصف (مثال: التاسع)
  classroom: string; // الفصل (مثال: 1)
  lessonTopic: string; // موضوع الدرس
  observerName: string; // اسم المقيم (المعلم الأول)
  scores: {
    [indicatorId: number]: EvaluationRating;
  };
  evidence: {
    [indicatorId: number]: string; // الشواهد المرصودة لكل مؤشر
  };
  generalStrengths: string[]; // جوانب الإجادة والأدلة من واقع الزيارة (Legacy / Compiled)
  generalDevelopments: string[]; // أولويات التطوير والأدلة من واقع الزيارة (Legacy / Compiled)
  recommendations: Recommendation[]; // التوصيات الإجرائية المصاغة (Legacy / Compiled)
  summaryNotes?: string; // ملاحظات عامة
  
  // Omani Portal Specific Fields
  visitNumber?: number; // رقم الزيارة
  period?: number; // الحصة (1-8)
  approved?: boolean; // معتمد
  schoolName?: string; // المدرسة
  civilId?: string; // الرقم الوظيفي / المدني للعميل
  generalStrengthsText?: string; // جوانب الإجادة في الأداء وأدلتها (1000 حرف)
  generalDevelopmentsText?: string; // الجوانب التي تحتاج إلى تطوير في الأداء وأدلتها (1000 حرف)
  supportProvided?: string; // الدعم المقدم (1000 حرف)
  recommendationsText?: string; // التوصيات (1000 حرف)
  selectedIndicators?: {
    [indicatorId: number]: boolean;
  };
}

